/** The "AI recommends — humans decide" banner. Use on every AI-generated surface. */
export function AIDisclaimer({ variant = "ai", className, children }: { variant?: "ai" | "human"; className?: string; children?: React.ReactNode }) {
  const ai = variant === "ai";
  const Icon = ai ? Bot : UserCheck;
  return (
    <div className={cn("flex items-start gap-3 rounded-xl border px-4 py-3 text-sm", ai ? "border-ai-400/25 bg-ai-500/[0.07] text-ai-300" : "border-saffron-400/30 bg-saffron-500/[0.07] text-saffron-300", className)}>
      <Icon className="mt-0.5 h-5 w-5 shrink-0" />
      <div>
        <p className="font-semibold tracking-wide">{ai ? "AI RECOMMENDATION — NOT FINAL DECISION" : "HUMAN DECISION REQUIRED"}</p>
        <p className="mt-0.5 text-slate-300/80">
          {children ?? (ai
            ? "Generated by StartupSetu AI agents for human review. AI cannot select a startup, sign a contract or release money."
            : "Final decisions on selection, contracts and payments are made by authorised officers and experts.")}
        </p>
      </div>
    </div>
  );
}

export function Alert({ tone = "warning", title, children, icon: Icon = ShieldAlert }: { tone?: "warning" | "error" | "info" | "success"; title: string; children?: React.ReactNode; icon?: LucideIcon }) {
  const t = { warning: "border-warn-400/30 bg-warn-500/[0.07] text-warn-400", error: "border-danger-400/30 bg-danger-500/[0.07] text-danger-400", info: "border-setu-400/30 bg-setu-500/[0.07] text-setu-300", success: "border-mint-400/30 bg-mint-500/[0.07] text-mint-400" }[tone];
  return (
    <div className={cn("flex items-start gap-3 rounded-xl border px-4 py-3 text-sm", t)} role="alert">
      <Icon className="mt-0.5 h-5 w-5 shrink-0" />
      <div><p className="font-semibold">{title}</p>{children && <div className="mt-0.5 text-slate-300/80">{children}</div>}</div>
    </div>
  );
}

