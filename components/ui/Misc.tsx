export function PageHeader({ title, subtitle, eyebrow, actions }: { title: string; subtitle?: string; eyebrow?: string; actions?: React.ReactNode }) {
  return (
    <motion.div initial={{ opacity: 0, y: 4 }} animate={{ opacity: 1, y: 0 }} transition={{ duration: 0.18 }} className="mb-6 flex flex-col gap-4 md:flex-row md:items-end md:justify-between">
      <div>
        {eyebrow && <p className="eyebrow mb-3">{eyebrow}</p>}
        <h1 className="font-display text-2xl font-semibold tracking-tight text-white md:text-[28px]">{title}</h1>
        {subtitle && <p className="mt-1.5 max-w-3xl text-sm text-slate-400 md:text-[15px]">{subtitle}</p>}
      </div>
      {actions && <div className="flex flex-wrap gap-2">{actions}</div>}
    </motion.div>
  );
}

export function Tabs<T extends string>({ tabs, value, onChange, className }: { tabs: readonly T[] | { id: T; label: string; count?: number }[]; value: T; onChange: (v: T) => void; className?: string }) {
  const items = (tabs as (T | { id: T; label: string; count?: number })[]).map((t) => (typeof t === "string" ? { id: t, label: t } : t)) as { id: T; label: string; count?: number }[];
  return (
    <div role="tablist" className={cn("flex flex-wrap gap-1 rounded-xl border border-white/[0.07] bg-ink-900/60 p-1", className)}>
      {items.map((t) => (
        <button
          key={t.id} role="tab" aria-selected={value === t.id} onClick={() => onChange(t.id)}
          className={cn("focus-ring relative rounded-lg px-3 py-1.5 text-sm transition-colors duration-100", value === t.id ? "text-white" : "text-slate-400 hover:text-slate-200")}
        >
          {value === t.id && <span className="absolute inset-0 rounded-lg bg-setu-500/15 ring-1 ring-setu-400/30" />}
          <span className="relative">{t.label}{t.count !== undefined && <span className="ml-1.5 text-xs text-slate-500">{t.count}</span>}</span>
        </button>
      ))}
    </div>
  );
}

